def _named() -> dict[str, str]:
    return _document()["named"]


def to_rgba(colour: Any, alpha: float | None = None) -> tuple[float, float, float, float]:
    """Parse *colour* into an ``(r, g, b, a)`` tuple of floats in 0..1.

    Accepted: a name (CSS4, ``"r"``/``"k"``/..., ``"C0"``..``"C9"``,
    ``"tab:blue"``), ``"#rgb"``/``"#rrggbb"``/``"#rrggbbaa"``, a grey level as
    a string (``"0.5"``), ``"none"`` (transparent), and a 3- or 4-sequence
    of floats in 0..1 -- or of integers in 0..255, which is how Qt-era code
    spells colours. *alpha*, when given, replaces the alpha channel.

    Raises
    ------
    ValueError
        When *colour* cannot be read as a colour.
    """
    rgba = _parse(colour)
    if alpha is not None:
        rgba = (*rgba[:3], float(alpha))
    return rgba


def _parse(colour: Any) -> tuple[float, float, float, float]:
    if isinstance(colour, str):
        text = colour.strip()
        lower = text.lower()
        if lower == "none":
            return (0.0, 0.0, 0.0, 0.0)
        named = _named()
        value = named.get(text, named.get(lower))
        if value is not None:
            return (*_hex_to_rgb(value), 1.0)
        if text.startswith("#"):
            digits = text[1:]
            if len(digits) in (3, 4):
                digits = "".join(2 * c for c in digits)
            if len(digits) in (6, 8):
                try:
                    channels = [int(digits[i:i + 2], 16) / 255.0 for i in range(0, len(digits), 2)]
                except ValueError:
                    pass
                else:
                    return tuple(channels) + ((1.0,) if len(channels) == 3 else ())  # type: ignore[return-value]
        try:
            level = float(text)
        except ValueError:
            raise ValueError(f"not a colour: {colour!r}") from None
        if 0.0 <= level <= 1.0:
            return (level, level, level, 1.0)
        raise ValueError(f"a grey level is 0..1, got {colour!r}")
    if isinstance(colour, Iterable):
        channels = list(colour)
        if len(channels) not in (3, 4):
            raise ValueError(f"a colour has 3 or 4 channels, got {colour!r}")
        if all(isinstance(c, int) and not isinstance(c, bool) for c in channels) and any(
            c > 1 for c in channels
        ):
            channels = [c / 255.0 for c in channels]
        values = [float(c) for c in channels]
        if any(not 0.0 <= c <= 1.0 for c in values):
            raise ValueError(f"colour channels are 0..1 (or integers 0..255), got {colour!r}")
        return tuple(values) + ((1.0,) if len(values) == 3 else ())  # type: ignore[return-value]
    raise ValueError(f"not a colour: {colour!r}")


def to_rgb(colour: Any) -> tuple[float, float, float]:
    """:func:`to_rgba` without the alpha channel."""
    return to_rgba(colour)[:3]  # type: ignore[return-value]


def to_rgba_bytes(colour: Any, alpha: float | None = None) -> tuple[int, int, int, int]:
    """:func:`to_rgba` as 0..255 integers."""
    return tuple(int(round(c * 255.0)) for c in to_rgba(colour, alpha))  # type: ignore[return-value]


def to_hex(colour: Any, keep_alpha: bool = False) -> str:
    """``"#rrggbb"`` (or ``"#rrggbbaa"`` with *keep_alpha*) for *colour*."""
    channels = to_rgba(colour)
    if not keep_alpha:
        channels = channels[:3]
    return "#" + "".join(f"{int(round(c * 255.0)):02x}" for c in channels)
